-- Relatório do Sienge publicado em formato incremental.
-- Antes cada publicação regravava o relatório inteiro (relatorio_importacoes) e cada navegador o baixava
-- inteiro de novo, o que pesava na cota de tráfego (egress) do Supabase. Agora:
--   • relatorio_linhas: uma linha por item do relatório, com a "chave" (impressão digital do conteúdo);
--   • relatorio_remocoes: as linhas que saíram do relatório (e em que momento);
--   • relatorio_versoes: cada publicação.
-- As três usam o mesmo contador (relatorio_seq): uma versão vale para tudo com seq menor ou igual ao dela,
-- e o navegador baixa só o que entrou ou saiu depois da versão que já tem guardada.
--
-- Acesso: copia as mesmas políticas de relatorio_importacoes (quem lê/publica hoje continua lendo/publicando).
-- A visão sienge_itens (Jarvis e status-solicitacoes do Estoque) passa a ler o formato novo e, enquanto não
-- houver nenhuma publicação nele, continua lendo relatorio_importacoes.
-- Pode rodar de novo.

create sequence if not exists public.relatorio_seq;

create table if not exists public.relatorio_linhas (
  id            bigint generated by default as identity primary key,
  seq           bigint not null default nextval('public.relatorio_seq'),
  chave         text not null,
  dados         jsonb not null,
  importado_por uuid default auth.uid(),
  importado_em  timestamptz not null default now()
);
create index if not exists relatorio_linhas_seq on public.relatorio_linhas (seq);

create table if not exists public.relatorio_remocoes (
  linha_id      bigint primary key references public.relatorio_linhas(id) on delete cascade,
  seq           bigint not null default nextval('public.relatorio_seq'),
  importado_por uuid default auth.uid(),
  removido_em   timestamptz not null default now()
);
create index if not exists relatorio_remocoes_seq on public.relatorio_remocoes (seq);

create table if not exists public.relatorio_versoes (
  versao        bigint primary key default nextval('public.relatorio_seq'),
  nome_arquivo  text,
  total_linhas  integer,
  seq_purgado   bigint not null default 0,
  importado_por uuid default auth.uid(),
  importado_em  timestamptz not null default now()
);

-- linha + momento em que saiu (null = ainda está no relatório)
create or replace view public.relatorio_linhas_estado with (security_invoker = true) as
  select l.id, l.seq, l.chave, l.dados, r.seq as seq_rem
    from public.relatorio_linhas l
    left join public.relatorio_remocoes r on r.linha_id = l.id;

grant usage, select on sequence public.relatorio_seq to authenticated, service_role;
grant select, insert, delete on public.relatorio_linhas, public.relatorio_remocoes, public.relatorio_versoes to authenticated, service_role;
grant select on public.relatorio_linhas_estado to authenticated, service_role;

-- mesmas permissões de relatorio_importacoes (RLS e políticas)
do $$
declare
  t text;
  p record;
  cmd text;
  rls boolean;
  leitura_anon boolean;
begin
  select c.relrowsecurity into rls from pg_class c join pg_namespace n on n.oid = c.relnamespace
   where n.nspname = 'public' and c.relname = 'relatorio_importacoes';
  select has_table_privilege('anon', 'public.relatorio_importacoes', 'select') into leitura_anon;
  foreach t in array array['relatorio_linhas', 'relatorio_remocoes', 'relatorio_versoes'] loop
    if coalesce(rls, false) then execute format('alter table public.%I enable row level security', t); end if;
    if leitura_anon then execute format('grant select on public.%I to anon', t); end if;
    for p in select * from pg_policies where schemaname = 'public' and tablename = 'relatorio_importacoes' loop
      execute format('drop policy if exists %I on public.%I', p.policyname, t);
      cmd := format('create policy %I on public.%I as %s for %s to %s', p.policyname, t, p.permissive, p.cmd,
                    (select string_agg(case when r = 'public' then 'public' else quote_ident(r) end, ', ') from unnest(p.roles) r));
      if p.qual is not null then cmd := cmd || ' using (' || p.qual || ')'; end if;
      if p.with_check is not null then cmd := cmd || ' with check (' || p.with_check || ')'; end if;
      execute cmd;
    end loop;
  end loop;
  if leitura_anon then execute 'grant select on public.relatorio_linhas_estado to anon'; end if;
end $$;

-- sienge_itens: mesma visão de antes (jarvis_num_jsonb.sql), agora sobre o formato novo
create or replace view public.sienge_itens with (security_invoker = true) as
 with ultima as (
   select versao, importado_em from public.relatorio_versoes order by versao desc limit 1
 ), linhas as (
   select u.importado_em, l.dados as value
     from ultima u
     join public.relatorio_linhas l on l.seq <= u.versao
    where not exists (select 1 from public.relatorio_remocoes r where r.linha_id = l.id and r.seq <= u.versao)
   union all
   select r.importado_em, e.value
     from public.relatorio_importacoes r
     cross join lateral jsonb_array_elements(r.dados) e(value)
    where not exists (select 1 from ultima)
      and not (r.lote is distinct from (select relatorio_importacoes.lote from public.relatorio_importacoes
                                         order by relatorio_importacoes.importado_em desc limit 1))
 )
 SELECT l.importado_em,
    (l.value ->> 'obra'::text) AS obra,
    split_part((l.value ->> 'obra'::text), ' - '::text, 1) AS codigo_obra,
    (l.value ->> 'numSolicitacao'::text) AS num_solicitacao,
    jarvis_data((l.value ->> 'dataSolicitacao'::text)) AS data_solicitacao,
    (l.value ->> 'situacaoSolicitacao'::text) AS situacao_solicitacao,
    (l.value ->> 'solicitante'::text) AS solicitante,
    (l.value ->> 'alcadaSolicitacao'::text) AS alcada_solicitacao,
    jarvis_data((l.value ->> 'dataAutorizacaoSolicitacao'::text)) AS data_autorizacao_solicitacao,
    (l.value ->> 'numPedido'::text) AS num_pedido,
    jarvis_data((l.value ->> 'dataPedido'::text)) AS data_pedido,
    (l.value ->> 'situacaoPedido'::text) AS situacao_pedido,
    (l.value ->> 'alcadaPedido'::text) AS alcada_pedido,
    (l.value ->> 'situacaoAutorizacaoPedido'::text) AS situacao_autorizacao_pedido,
    (l.value ->> 'situacaoAutorizacaoItem'::text) AS situacao_autorizacao_item,
    jarvis_data((l.value ->> 'dataAutorizacaoPedido'::text)) AS data_autorizacao_pedido,
    (l.value ->> 'comprador'::text) AS comprador,
    (l.value ->> 'compradorDistribuido'::text) AS comprador_distribuido,
    (l.value ->> 'fornecedor'::text) AS fornecedor,
    (l.value ->> 'grupoInsumo'::text) AS grupo_insumo,
    (l.value ->> 'descricaoInsumo'::text) AS descricao_insumo,
    (l.value ->> 'detalhe'::text) AS detalhe,
    (l.value ->> 'marca'::text) AS marca,
    (l.value ->> 'unidadeMovimento'::text) AS unidade,
    jarvis_num((l.value -> 'qtdSolicitada'::text)) AS qtd_solicitada,
    jarvis_num((l.value -> 'qtdEntregue'::text)) AS qtd_entregue,
    jarvis_num((l.value -> 'saldo'::text)) AS saldo,
    jarvis_data((l.value ->> 'previsaoEntrega'::text)) AS previsao_entrega,
    jarvis_data((l.value ->> 'dataChegadaObra'::text)) AS data_chegada_obra,
    jarvis_data((l.value ->> 'dataEntregaObra'::text)) AS data_entrega_obra,
    (l.value ->> 'numNotaFiscal'::text) AS num_nota_fiscal,
    jarvis_data((l.value ->> 'dataNotaFiscal'::text)) AS data_nota_fiscal,
    jarvis_num((l.value -> 'valorNota'::text)) AS valor_nota,
    (l.value ->> 'chaveNFe'::text) AS chave_nfe,
    (l.value ->> 'anexoNotaFiscal'::text) AS anexo_nota_fiscal,
    (l.value ->> 'situacaoPagamento'::text) AS situacao_pagamento,
    jarvis_num((l.value -> 'numParcelas'::text)) AS num_parcelas
   FROM linhas l;
