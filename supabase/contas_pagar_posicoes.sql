-- Contas a pagar (Previsto × Realizado → Financeiro): posições importadas
-- do relatório de contas a pagar por vencimento do Sienge (.csv). Cada
-- importação grava uma linha por data de cálculo do relatório ("Calcular
-- acréscimos até"); o painel usa a mais recente.
--
-- dados = { fields: ['venc','credor','doc','lanc','total'], rows: [[...]] }
-- venc em ISO (aaaa-mm-dd); doc é o documento do Sienge ("PCT. 512",
-- "PPC. 59178", "NFE. 51627"...), de onde sai o tipo e o número.
--
-- Leitura, importação e exclusão: só admin ou supervisor
-- (private.is_gestor_credito) — o grupo Financeiro do painel é restrito a
-- eles. Sem esta tabela o painel continua funcionando, guardando a
-- importação só no navegador. Pode rodar de novo: recria as políticas.

create table if not exists public.contas_pagar_posicoes (
  id            bigint generated by default as identity primary key,
  data_ref      date not null unique,
  nome_arquivo  text,
  periodo       text,
  total_titulos integer,
  dados         jsonb not null,
  importado_por uuid default auth.uid(),
  importado_em  timestamptz not null default now()
);

alter table public.contas_pagar_posicoes enable row level security;

drop policy if exists "leitura contas a pagar" on public.contas_pagar_posicoes;
create policy "leitura contas a pagar" on public.contas_pagar_posicoes
  for select using (private.is_gestor_credito(auth.uid()));

drop policy if exists "grava contas a pagar" on public.contas_pagar_posicoes;
create policy "grava contas a pagar" on public.contas_pagar_posicoes
  for insert with check (private.is_gestor_credito(auth.uid()));

drop policy if exists "edita contas a pagar" on public.contas_pagar_posicoes;
create policy "edita contas a pagar" on public.contas_pagar_posicoes
  for update using (private.is_gestor_credito(auth.uid()))
  with check (private.is_gestor_credito(auth.uid()));

drop policy if exists "exclui contas a pagar" on public.contas_pagar_posicoes;
create policy "exclui contas a pagar" on public.contas_pagar_posicoes
  for delete using (private.is_gestor_credito(auth.uid()));
