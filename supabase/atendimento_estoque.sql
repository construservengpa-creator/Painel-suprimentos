-- Atendimento de solicitações pelo estoque (almoxarifado).
-- O relatório do Sienge que alimenta o painel (sienge_relatorio-*.xlsx) não traz a quantidade atendida
-- por reserva/transferência de estoque: uma solicitação "Parcialmente atendida" sem pedido de compra
-- aparece com TODAS as linhas iguais (sem quantidade entregue nem saldo), e o painel contava todas como
-- pendentes. O PDF "Acompanhamento de Solicitações" do Sienge traz, por insumo, a quantidade reservada e a
-- atendida. O painel lê esse PDF e grava aqui um retrato por solicitação (cada nova importação substitui
-- as linhas das solicitações que vieram no PDF). Ao carregar o relatório, a linha da solicitação sem pedido
-- cujo insumo já foi atendido por inteiro pelo estoque sai das pendências.
--
-- chave = "<solicitação>§<código do insumo>§<descrição + detalhe + marca sem acento/pontuação>"
-- (a mesma montada pelo painel em chaveAtendEstoque()).
--
-- Leitura aberta (como entregas_outro_centro); gravação com admin, supervisor ou operador avançado
-- (private.pode_lancar_cap). Pode rodar de novo.

create table if not exists public.solicitacoes_atendimento_estoque (
  id               bigint generated by default as identity primary key,
  chave            text not null unique,
  num_solicitacao  text not null,
  insumo_codigo    text,
  insumo           text,
  unidade          text,
  qtd_solicitada   numeric,
  qtd_reservada    numeric,
  qtd_atendida     numeric not null default 0,
  obra             text,
  situacao         text,
  arquivo          text,
  atualizado_por   uuid default auth.uid(),
  atualizado_em    timestamptz not null default now()
);
create index if not exists solic_atend_estoque_num on public.solicitacoes_atendimento_estoque (num_solicitacao);

alter table public.solicitacoes_atendimento_estoque enable row level security;

drop policy if exists "leitura atendimento estoque" on public.solicitacoes_atendimento_estoque;
create policy "leitura atendimento estoque" on public.solicitacoes_atendimento_estoque
  for select using (true);

drop policy if exists "grava atendimento estoque" on public.solicitacoes_atendimento_estoque;
create policy "grava atendimento estoque" on public.solicitacoes_atendimento_estoque
  for insert with check (private.pode_lancar_cap(auth.uid()));

drop policy if exists "edita atendimento estoque" on public.solicitacoes_atendimento_estoque;
create policy "edita atendimento estoque" on public.solicitacoes_atendimento_estoque
  for update using (private.pode_lancar_cap(auth.uid()))
  with check (private.pode_lancar_cap(auth.uid()));

drop policy if exists "exclui atendimento estoque" on public.solicitacoes_atendimento_estoque;
create policy "exclui atendimento estoque" on public.solicitacoes_atendimento_estoque
  for delete using (private.pode_lancar_cap(auth.uid()));

grant select on public.solicitacoes_atendimento_estoque to anon, authenticated;
grant insert, update, delete on public.solicitacoes_atendimento_estoque to authenticated;
