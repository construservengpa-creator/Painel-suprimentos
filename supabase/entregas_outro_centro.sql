-- Entrega em outro centro de custo: o item foi solicitado/comprado por um
-- centro de custo, mas a entrega vai acontecer em outro. O painel guarda
-- aqui o centro de custo da entrega e, ao carregar o relatório do Sienge,
-- mostra a pendência nesse centro de custo (o de origem continua indicado
-- no item).
--
-- Chave do item: "S:<solicitação>§<insumo>" (ou "P:<pedido>§<insumo>"
-- quando a linha não tem solicitação), normalizada sem acento e em
-- maiúsculas — a mesma montada pelo painel em chaveEntregaCentro().
--
-- Leitura aberta (como insumos_criticos), para o relatório publicado já
-- sair com a pendência no centro de custo certo; gravação com admin,
-- supervisor ou operador avançado (private.pode_lancar_cap).

create table if not exists public.entregas_outro_centro (
  id            bigint generated by default as identity primary key,
  chave         text not null unique,
  num_solicitacao text,
  num_pedido    text,
  insumo        text,
  obra_origem   text,
  obra_destino  text not null,
  observacao    text,
  atualizado_por uuid default auth.uid(),
  atualizado_em timestamptz not null default now()
);

alter table public.entregas_outro_centro enable row level security;

drop policy if exists "leitura entregas outro centro" on public.entregas_outro_centro;
create policy "leitura entregas outro centro" on public.entregas_outro_centro
  for select using (true);

drop policy if exists "grava entregas outro centro" on public.entregas_outro_centro;
create policy "grava entregas outro centro" on public.entregas_outro_centro
  for insert with check (private.pode_lancar_cap(auth.uid()));

drop policy if exists "edita entregas outro centro" on public.entregas_outro_centro;
create policy "edita entregas outro centro" on public.entregas_outro_centro
  for update using (private.pode_lancar_cap(auth.uid()))
  with check (private.pode_lancar_cap(auth.uid()));

drop policy if exists "exclui entregas outro centro" on public.entregas_outro_centro;
create policy "exclui entregas outro centro" on public.entregas_outro_centro
  for delete using (private.pode_lancar_cap(auth.uid()));
