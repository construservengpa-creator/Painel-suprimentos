-- Contas a pagar → complemento: relatório de títulos do Sienge (.xlsx, uma
-- linha por título). O painel guarda só os títulos em aberto (Valor a pagar
-- > 0) e os cruza com o relatório por vencimento (contas_pagar_posicoes)
-- pelo documento ("PICT" + "ISS - T 4155") e pelo credor, para trazer
-- empresa, origem, documento previsão, ciência, anexo, consistência,
-- valores do título (original, pago, a pagar, impostos) e observação.
--
-- dados = { fields: ['tit','tipo','ndoc','credor',...], rows: [[...]] }
--
-- Mesmas regras de acesso de contas_pagar_posicoes: só admin ou supervisor
-- (private.is_gestor_credito). Sem esta tabela o painel guarda a importação
-- só no navegador. Pode rodar de novo: recria as políticas.

create table if not exists public.contas_pagar_titulos (
  id            bigint generated by default as identity primary key,
  data_ref      date not null unique,
  nome_arquivo  text,
  total_titulos integer,
  dados         jsonb not null,
  importado_por uuid default auth.uid(),
  importado_em  timestamptz not null default now()
);

alter table public.contas_pagar_titulos enable row level security;

drop policy if exists "leitura titulos contas a pagar" on public.contas_pagar_titulos;
create policy "leitura titulos contas a pagar" on public.contas_pagar_titulos
  for select using (private.is_gestor_credito(auth.uid()));

drop policy if exists "grava titulos contas a pagar" on public.contas_pagar_titulos;
create policy "grava titulos contas a pagar" on public.contas_pagar_titulos
  for insert with check (private.is_gestor_credito(auth.uid()));

drop policy if exists "edita titulos contas a pagar" on public.contas_pagar_titulos;
create policy "edita titulos contas a pagar" on public.contas_pagar_titulos
  for update using (private.is_gestor_credito(auth.uid()))
  with check (private.is_gestor_credito(auth.uid()));

drop policy if exists "exclui titulos contas a pagar" on public.contas_pagar_titulos;
create policy "exclui titulos contas a pagar" on public.contas_pagar_titulos
  for delete using (private.is_gestor_credito(auth.uid()));
